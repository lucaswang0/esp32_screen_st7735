#include "st7735_driver.h"

// ============================================================
//  SPI 对象
// ============================================================
static SPIClass spi = SPIClass(FSPI);

// ============================================================
//  底层 SPI 函数
// ============================================================
static void writeCmd(uint8_t cmd) {
  digitalWrite(PIN_CS, LOW);
  digitalWrite(PIN_DC, LOW);
  spi.transfer(cmd);
  digitalWrite(PIN_CS, HIGH);
}

static void writeData(uint8_t data) {
  digitalWrite(PIN_CS, LOW);
  digitalWrite(PIN_DC, HIGH);
  spi.transfer(data);
  digitalWrite(PIN_CS, HIGH);
}

static uint16_t fixColor(uint16_t color) {
  return ((color & 0x001F) << 11) | (color & 0x07E0) | ((color & 0xF800) >> 11);
}

// ============================================================
//  绘图函数
// ============================================================
static void setAddrWindow(uint16_t x, uint16_t y, uint16_t w, uint16_t h) {
  // 应用屏幕偏移
  x += TFT_X_OFFSET;
  y += TFT_Y_OFFSET;
  
  writeCmd(0x2A);
  writeData(x >> 8); writeData(x & 0xFF);
  writeData((x + w - 1) >> 8); writeData((x + w - 1) & 0xFF);
  writeCmd(0x2B);
  writeData(y >> 8); writeData(y & 0xFF);
  writeData((y + h - 1) >> 8); writeData((y + h - 1) & 0xFF);
  writeCmd(0x2C);
}

void fillScreen(uint16_t color) {
  uint16_t c = fixColor(color);
  setAddrWindow(0, 0, TFT_WIDTH, TFT_HEIGHT);
  digitalWrite(PIN_CS, LOW);
  digitalWrite(PIN_DC, HIGH);
  for (int i = 0; i < 20480; i++) {
    spi.transfer16(c);
  }
  digitalWrite(PIN_CS, HIGH);
}

void drawPixel(int16_t x, int16_t y, uint16_t color) {
  if (x < 0 || x >= TFT_WIDTH || y < 0 || y >= TFT_HEIGHT) return;
  uint16_t c = fixColor(color);
  setAddrWindow(x, y, 1, 1);
  digitalWrite(PIN_CS, LOW);
  digitalWrite(PIN_DC, HIGH);
  spi.transfer16(c);
  digitalWrite(PIN_CS, HIGH);
}

void fillRect(int16_t x, int16_t y, int16_t w, int16_t h, uint16_t color) {
  if (w <= 0 || h <= 0) return;
  if (x + w > TFT_WIDTH) w = TFT_WIDTH - x;
  if (y + h > TFT_HEIGHT) h = TFT_HEIGHT - y;
  if (w <= 0 || h <= 0) return;
  
  uint16_t c = fixColor(color);
  setAddrWindow(x, y, w, h);
  digitalWrite(PIN_CS, LOW);
  digitalWrite(PIN_DC, HIGH);
  for (int i = 0; i < w * h; i++) {
    spi.transfer16(c);
  }
  digitalWrite(PIN_CS, HIGH);
}

void drawRect(int16_t x, int16_t y, int16_t w, int16_t h, uint16_t color) {
  if (w <= 0 || h <= 0) return;
  if (x + w > TFT_WIDTH) w = TFT_WIDTH - x;
  if (y + h > TFT_HEIGHT) h = TFT_HEIGHT - y;
  if (w <= 0 || h <= 0) return;
  
  drawLine(x, y, x + w - 1, y, color);
  drawLine(x, y + h - 1, x + w - 1, y + h - 1, color);
  drawLine(x, y, x, y + h - 1, color);
  drawLine(x + w - 1, y, x + w - 1, y + h - 1, color);
}

void drawLine(int16_t x0, int16_t y0, int16_t x1, int16_t y1, uint16_t color) {
  int16_t dx = abs(x1 - x0), sx = x0 < x1 ? 1 : -1;
  int16_t dy = abs(y1 - y0), sy = y0 < y1 ? 1 : -1;
  int16_t err = (dx > dy ? dx : -dy) / 2, e2;
  
  for (;;) {
    drawPixel(x0, y0, color);
    if (x0 == x1 && y0 == y1) break;
    e2 = err;
    if (e2 > -dx) { err -= dy; x0 += sx; }
    if (e2 < dy) { err += dx; y0 += sy; }
  }
}

void drawCircle(int16_t x0, int16_t y0, int16_t r, uint16_t color) {
  int16_t x = -r, y = 0, err = 2 - 2 * r;
  
  do {
    drawPixel(x0 - x, y0 + y, color);
    drawPixel(x0 + x, y0 + y, color);
    drawPixel(x0 + x, y0 - y, color);
    drawPixel(x0 - x, y0 - y, color);
    
    int16_t e2 = err;
    if (e2 <= y) { err += ++y * 2 + 1; }
    if (e2 > x || err > y) { err += ++x * 2 + 1; }
  } while (x <= 0);
}

