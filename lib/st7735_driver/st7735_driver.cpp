// ============================================================
//  文字渲染
// ============================================================
void drawChar(int16_t x, int16_t y, char c, uint16_t color, uint16_t bg, uint8_t size) {
  if (c < 32 || c > 126) c = ' ';
  uint8_t idx = c - 32;
  
  for (uint8_t col = 0; col < 8; col++) {
    for (uint8_t row = 0; row < 16; row++) {
      if (font8x16[idx][row] & (0x80 >> col)) {
        fillRect(x + col * size, y + row * size, size, size, color);
      }
    }
  }
}

void drawText(int16_t x, int16_t y, const char* text, uint16_t color, uint16_t bg, uint8_t size) {
  int i = 0;
  while (text[i] != '\0') {
    drawChar(x + i * (8 * size + 2), y, text[i], color, bg, size);
    i++;
  }
}


// ============================================================
//  图片显示（彩色图片）
// ============================================================
void drawImage(int16_t x, int16_t y, int16_t w, int16_t h, const uint16_t* image) {
  if (x + w > TFT_WIDTH || y + h > TFT_HEIGHT) return;
  if (x < 0 || y < 0) return;
  
  setAddrWindow(x, y, w, h);
  digitalWrite(PIN_CS, LOW);
  digitalWrite(PIN_DC, HIGH);
  
  for (int i = 0; i < w * h; i++) {
    uint16_t color = image[i];
    spi.transfer16(color);
  }
  digitalWrite(PIN_CS, HIGH);
}

// RGB565 图片显示（uint8_t 格式，每像素2字节）
void drawImageRGB565(int16_t x, int16_t y, int16_t w, int16_t h, const uint8_t* image) {
  if (x + w > TFT_WIDTH || y + h > TFT_HEIGHT) return;
  if (x < 0 || y < 0) return;
  
  setAddrWindow(x, y, w, h);
  digitalWrite(PIN_CS, LOW);
  digitalWrite(PIN_DC, HIGH);
  
  for (int i = 0; i < w * h * 2; i += 2) {
    // LVGL 生成的数据是低字节在前，需要交换
    uint16_t color = (image[i + 1] << 8) | image[i];
    spi.transfer16(color);
  }
  digitalWrite(PIN_CS, HIGH);
}

// ============================================================
//  图片显示（单色图片）
// ============================================================
void drawImageMonochrome(int16_t x, int16_t y, int16_t w, int16_t h, const uint8_t* image, uint16_t color, uint16_t bg) {
  if (x + w > TFT_WIDTH || y + h > TFT_HEIGHT) return;
  if (x < 0 || y < 0) return;
  
  uint16_t c = fixColor(color);
  uint16_t b = fixColor(bg);
  
  for (int16_t row = 0; row < h; row++) {
    for (int16_t col = 0; col < w; col++) {
      uint16_t byteIndex = row * ((w + 7) / 8) + col / 8;
      uint8_t bitIndex = 7 - (col % 8);
      
      if (image[byteIndex] & (1 << bitIndex)) {
        drawPixel(x + col, y + row, color);
      } else {
        drawPixel(x + col, y + row, bg);
      }
    }
  }
}

// ============================================================
//  工具函数
// ============================================================
uint16_t color565(uint8_t r, uint8_t g, uint8_t b) {
  return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3);
}

// ============================================================
//  初始化
// ============================================================
void tftInit() {
  pinMode(PIN_BL, OUTPUT);
  digitalWrite(PIN_BL, HIGH);

  pinMode(PIN_RST, OUTPUT);
  digitalWrite(PIN_RST, LOW);
  delay(100);
  digitalWrite(PIN_RST, HIGH);
  delay(150);

  spi.begin(PIN_SCLK, PIN_MISO, PIN_MOSI, PIN_CS);
  spi.setFrequency(16000000);

  pinMode(PIN_DC, OUTPUT);
  pinMode(PIN_CS, OUTPUT);
  digitalWrite(PIN_CS, HIGH);

  writeCmd(0x01); delay(150);
  writeCmd(0x11); delay(120);
  writeCmd(0x36); writeData(0x00);
  writeCmd(0x3A); writeData(0x05);
  writeCmd(0x29); delay(100);

  fillScreen(C_BLACK);
}